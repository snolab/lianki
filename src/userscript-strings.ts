/** The strings for the browser's language (one of the 16; English otherwise). */
export const userscriptStrings = (lang?: string | null): UserscriptStrings =>
  USERSCRIPT_STRINGS[pillChatLang(lang)];

/** `{name}` placeholders filled in. */
export const fillUs = (s: string, vars: Record<string, string | number>): string =>
  s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));

/**
 * A failure as the user reads it: offline, sign in, server busy, or anything
 * else. The raw message (status, endpoint, error id) stays in the "Copy error
 * details" payload and the console, never on screen.
 */
export function friendlyError(raw: string | null | undefined, t: UserscriptStrings): string {
  const s = String(raw ?? "");
  if (/Network error|timed out|aborted|Failed to fetch|offline/i.test(s)) return t.errOffline;
  if (/Login required|\b401\b/.test(s)) return t.errSignIn;
  if (/HTTP 5\d\d/.test(s)) return t.errServer;
  return t.errOther;
}
