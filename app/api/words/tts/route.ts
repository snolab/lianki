import { NextRequest, NextResponse } from "next/server";
import crypto from "crypto";
import { authUserOrNull } from "@/app/signInEmail";
import { devBridgeUser } from "@/lib/dev-bridge-user";
import {
  isWorkersAiConfigured,
  MELOTTS_LANGS,
  sniffAudioType,
  speechModel,
  workersAiSpeech,
} from "@/lib/workers-ai";
import { checkRateLimit } from "@/lib/rateLimit";
import { logSanitizedError } from "@/lib/safeError";
import { getCachedTTS, getVoiceClip, putCachedTTS } from "@/lib/ttsCache";
import { VOICE_CREDITS, voiceKey } from "@/lib/voice";
import { MAX_TTS_TEXT, ttsParams } from "@/lib/voice-clip";

/**
 * Word audio for /words: the word, its meaning and its example, each a clip.
 * The client prefetches the clips of the rows near the screen
 * (lib/words/audio-cache.ts), so a tap plays at once.
 *
 * Word-list clips come pre-rendered with open voices (lib/voice.ts,
 * scripts/voice) — better than MeloTTS, and free to serve. In production the
 * edge Worker in front of this route (workers/voice) serves them, public and
 * edge-cached, before a request ever reaches here; what it does not have
 * comes through to this route. Anything else is generated by MeloTTS on
 * first request.
 *
 * Cost: each (lang, text) is generated once, ever — kept in R2 and then in
 * the browser's HTTP cache for a year. Only cache misses are rate limited,
 * and text is capped at an example sentence's length.
 */
const MAX_TEXT = MAX_TTS_TEXT;
const MISS_WINDOW_MS = 10 * 60_000;
// The server voice is the default: a fast session of new words (word + example
// each) must fit. Cached clips never count.
const MISS_MAX = 600;
const CACHE_HEADERS = { "Cache-Control": "private, max-age=31536000, immutable" };
/** A recording is of a bundled, public word list: anyone may cache it (as workers/voice does). */
const PUBLIC_CACHE_HEADERS = { "Cache-Control": "public, max-age=31536000, immutable" };

export const GET = async (req: NextRequest) => {
  // The owner's dev server (lib/dev-bridge-user.ts) may ask as the owner; a
  // wrong bridge header is refused, never answered from the cookie.
  const bridged = await devBridgeUser(req);
  const user = bridged === undefined ? await authUserOrNull() : bridged;
  if (!user?.email) return NextResponse.json({ error: "Login required" }, { status: 401 });

  const { lang, text } = ttsParams(req.nextUrl.searchParams);
  if (!text || text.length > MAX_TEXT)
    return NextResponse.json({ error: `text: 1–${MAX_TEXT} characters` }, { status: 400 });

  try {
    const clip = await getVoiceClip(voiceKey(lang, text));
    if (clip)
      return new Response(Buffer.from(clip), {
        headers: { "Content-Type": "audio/mpeg", "X-Voice": "recorded", ...PUBLIC_CACHE_HEADERS },
      });
  } catch (err) {
    logSanitizedError("words.tts.voice.lookup", err, {});
  }

  // 404, not 400: the client remembers the language has no server voice —
  // unless only this text is missing (X-Voice: miss).
  if (!MELOTTS_LANGS.has(lang))
    return VOICE_CREDITS[lang]
      ? NextResponse.json(
          { error: "No recording of this text" },
          { status: 404, headers: { "X-Voice": "miss" } },
        )
      : NextResponse.json({ error: "No voice for this language" }, { status: 404 });

  const key = crypto
    .createHash("sha256")
    .update(`${speechModel()}:words:${lang}:${text}`)
    .digest("hex");
  try {
    const cached = await getCachedTTS(key);
    if (cached)
      return new Response(Buffer.from(cached), {
        headers: {
          "Content-Type": sniffAudioType(Buffer.from(cached)),
          "X-Voice": "melotts-cached",
          ...CACHE_HEADERS,
        },
      });
  } catch (err) {
    logSanitizedError("words.tts.cache.lookup", err, {});
  }

  const limit = checkRateLimit(`words-tts:${user.email}`, {
    windowMs: MISS_WINDOW_MS,
    max: MISS_MAX,
  });
  if (!limit.allowed)
    return NextResponse.json(
      { error: "Too many new words to voice; retry later" },
      { status: 429, headers: { "Retry-After": String(Math.ceil(limit.retryAfterMs / 1000)) } },
    );
  if (!isWorkersAiConfigured())
    return NextResponse.json({ error: "Speech is not configured" }, { status: 503 });

  try {
    const { audio, contentType } = await workersAiSpeech({ text, lang, signal: req.signal });
    try {
      await putCachedTTS(key, audio, { lang, textLength: text.length, source: "words" });
    } catch (err) {
      logSanitizedError("words.tts.cache.save", err, {});
    }
    return new Response(audio, {
      headers: { "Content-Type": contentType, "X-Voice": "melotts", ...CACHE_HEADERS },
    });
  } catch (err) {
    logSanitizedError("words.tts.generate", err, {});
    return NextResponse.json({ error: "Failed to generate speech" }, { status: 502 });
  }
};
