export type IconName = keyof typeof ICONS;

type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & {
  name: IconName;
  /** "fill" falls back to "regular" for icons that carry no fill paths. */
  weight?: "regular" | "fill";
  /** Accessible name; without one the icon is decorative (aria-hidden). */
  label?: string;
};

/** A 1em icon in currentColor, so it sits in text like the glyph it replaces. */
export function Icon({ name, weight = "regular", label, className, ...rest }: IconProps) {
  const icon: Paths = ICONS[name];
  const paths = (weight === "fill" && icon.fill) || icon.regular;
  return (
    <svg
      data-icon={name}
      viewBox="0 0 256 256"
      fill="currentColor"
      width="1em"
      height="1em"
      className={`inline-block shrink-0 align-[-0.125em] ${className ?? ""}`}
      {...(label ? { role: "img", "aria-label": label } : { "aria-hidden": true })}
      {...rest}
    >
      {paths.map((d) => (
        <path key={d} d={d} />
      ))}
    </svg>
  );
}

/**
 * The selected state (style C): a seal-red stamp (印章) with the filled icon
 * carved out of it, so the paper itself shows through the glyph — no box or
 * light fill behind it. 1.5em square; size follows the font size.
 */
export function SealIcon({ name, className }: { name: IconName; className?: string }) {
  const mask = `lk-seal-${useId().replace(/[^\w-]/g, "")}`;
  const icon: Paths = ICONS[name];
  return (
    <svg
      aria-hidden
      data-icon={name}
      viewBox="-64 -64 384 384"
      className={`lk-seal ${className ?? ""}`}
    >
      <mask id={mask}>
        <rect x="-64" y="-64" width="384" height="384" fill="oklch(1 0 0)" />
        {(icon.fill ?? icon.regular).map((d) => (
          <path key={d} d={d} fill="oklch(0 0 0)" />
        ))}
      </mask>
      <rect
        x="-56"
        y="-56"
        width="368"
        height="368"
        rx="40"
        fill="currentColor"
        mask={`url(#${mask})`}
      />
    </svg>
  );
}
