/**
 * Generates lib/state-tree.generated.ts from docs/state-tree.md, the
 * hand-edited outline of what is in flight and what waits on the owner.
 *
 * Same reason as scripts/gen-blog-corpus.ts: the Worker has no filesystem, so
 * GET /api/dev/state-tree can only serve a copy the bundler inlined. Run by
 * scripts/pre-commit.ts on every commit (by hand:
 * `bun -e 'require("./scripts/gen-state-tree").writeStateTree()'`); unit/state-tree.test.ts fails if the two drift.
 */
import { execSync } from "child_process";
import { existsSync, readFileSync, writeFileSync } from "fs";
import { join } from "path";

export const STATE_TREE_PATH = "docs/state-tree.md";
export const STATE_TREE_MODULE = "lib/state-tree.generated.ts";

export function renderModule(md: string): string {
  return (
    `// Generated by scripts/gen-state-tree.ts from ${STATE_TREE_PATH} — do not edit by hand.\n` +
    `// Inlined because the Worker has no filesystem to read the markdown from.\n` +
    `export const STATE_TREE_MD: string = ${JSON.stringify(md)};\n`
  );
}

/** Write the module, formatted as oxfmt would (lint-staged formats it the same way). */
export function writeStateTree(root = process.cwd()): { changed: boolean } {
  const path = join(root, STATE_TREE_MODULE);
  const prev = existsSync(path) ? readFileSync(path, "utf-8") : "";
  writeFileSync(path, renderModule(readFileSync(join(root, STATE_TREE_PATH), "utf-8")));
  execSync(`bunx oxfmt "${path}"`, { stdio: "ignore" });
  return { changed: readFileSync(path, "utf-8") !== prev };
}
